def main():
    args = parse_args()

    weights_b64 = npz_to_b64(args.weights)
    examples_b64 = build_examples_npz_b64(args.shd_h5, args.n_examples, args.seed)
    model_src = read_model_src()

    script = TEMPLATE.format(
        n_examples=args.n_examples,
        weights_b64=weights_b64,
        examples_b64=examples_b64,
        model_src=model_src,
    )

    with open(args.out, "w") as f:
        f.write(script)

    print(f"Generated {args.out} ({len(script)} bytes)")


if __name__ == "__main__":
    main()
