"""
Generates a fully self-contained Python script for submission as a SpiNNaker
batch job via nmpi (see notebooks/spinnaker_lif_shd_deploy.ipynb). The job
runner sandbox only sees the single uploaded file, so this embeds:
  - the exported+folded sparch weights (base64-encoded .npz bytes)
  - a handful of real SHD test examples' spike times (same encoding)
  - the pynn_lif_model.py network-building logic, inlined as source
  - a small driver that builds the network with pyNN.spiNNaker, runs it,
    and prints per-example predictions + a summary accuracy line.

Usage:
    python generate_spinnaker_script.py --weights PATH --shd_h5 PATH
        --n_examples N --seed N --out OUT.py
"""
import argparse
import base64
import io
import os

import h5py
import numpy as np

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_SRC_PATH = os.path.join(REPO_ROOT, "src", "pynn_lif_model.py")


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--weights",
        default=os.path.join(REPO_ROOT, "src", "data", "shd_lif_weights.npz"),
    )
    parser.add_argument(
        "--shd_h5",
        default=os.path.join(
            os.path.dirname(REPO_ROOT), "sparch", "shd_dataset", "shd_test.h5"
        ),
    )
    parser.add_argument("--n_examples", type=int, default=10)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--out",
        default=os.path.join(REPO_ROOT, "spinnaker_job_generated.py"),
    )
    return parser.parse_args()


def npz_to_b64(npz_path):
    with open(npz_path, "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")


def build_examples_npz_b64(shd_h5_path, n_examples, seed):
    f = h5py.File(shd_h5_path, "r")
    times = f["spikes"]["times"]
    units = f["spikes"]["units"]
    labels = np.array(f["labels"])

    rng = np.random.default_rng(seed)
    indices = rng.choice(len(labels), size=n_examples, replace=False)

    out = {}
    for j, i in enumerate(indices):
        out[f"example{j}_times"] = np.array(times[i])
        out[f"example{j}_units"] = np.array(units[i])
        out[f"example{j}_label"] = int(labels[i])
    out["n_examples"] = n_examples

    buf = io.BytesIO()
    np.savez(buf, **out)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def read_model_src():
    with open(MODEL_SRC_PATH) as f:
        src = f.read()
    # Strip the module docstring's leading import line duplication concerns --
    # keep as-is, the generated script re-imports numpy/scipy itself anyway.
    return src


